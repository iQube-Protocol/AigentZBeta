/**
 * Reciprocal Artifact Exchange — the generic type contract (PRD-IRL-AX-001).
 *
 * A GENERIC IRL capability: a bilateral, receipted exchange of independently
 * frozen research artifacts between two collaborating parties, gated by a
 * reciprocal disclosure policy and a lightweight signing ritual. This is NOT
 * an architecture-specific or OCSGA-specific feature — IRL-AX-001 (CI/IRL ×
 * OCSGA) is the first dogfood INSTANCE of this primitive, never baked into
 * the type/state-machine shape below.
 *
 * ── THE EVIDENTIARY CLAIM DISCIPLINE (PRD §2, non-negotiable) ───────────────
 *
 * The system may truthfully state: "Both artifacts were independently frozen
 * before formal exchange." It must NEVER state or imply that neither party
 * had prior knowledge of, discussion about, or access to the other's ideas —
 * that is a claim of informational isolation this capability does not and
 * cannot establish. `FORBIDDEN_ISOLATION_PHRASES` + `assertNoIsolationClaim`
 * below are the enforcement point; every UI string, receipt summary and
 * evidence record generated by this capability MUST pass that guard, and
 * `tests/reciprocal-exchange.test.ts` asserts it directly.
 *
 * ── STORAGE ──────────────────────────────────────────────────────────────
 *
 * Persisted in dedicated tables (supabase/migrations/*_reciprocal_artifact_
 * exchange.sql): `reciprocal_exchanges`, `exchange_artifacts`,
 * `exchange_attestations`, `exchange_receipts`, `exchange_comparisons`,
 * `exchange_derivatives`. Service-role RLS only — every read/write goes
 * through services/research/reciprocalExchange.ts, which resolves the caller
 * through the identity spine first (never a client-side Supabase read).
 */

// ─── State machine (PRD §11) ─────────────────────────────────────────────────

export const EXCHANGE_STATES = [
  'DRAFT',
  'A_DEPOSITED',
  'INVITED',
  'B_JOINED',
  'B_DEPOSITED',
  'READY_TO_SIGN',
  'A_SIGNED',
  'B_SIGNED',
  'EXCHANGED',
  'RECEIPT_ACKNOWLEDGED',
  'COMPARISON_OPEN',
  'COMPLETED',
] as const;
export type ExchangeState = (typeof EXCHANGE_STATES)[number];

/** Terminal/exception states (PRD §11). Reachable from most non-terminal
 *  states; never reachable FROM a terminal state (this file's transition
 *  table is the single source of truth for exactly which). */
export const EXCHANGE_EXCEPTION_STATES = [
  'DECLINED',
  'WITHDRAWN_PRE_EXCHANGE',
  'ARTIFACT_REPLACEMENT_REQUIRED',
  'SIGNATURE_EXPIRED',
  'DISPUTED',
  'REVOKED_ACCESS_POST_EXCHANGE',
] as const;
export type ExchangeExceptionState = (typeof EXCHANGE_EXCEPTION_STATES)[number];

export type ExchangeStatus = ExchangeState | ExchangeExceptionState;

/** States at/after which the exchange has crossed (reciprocal disclosure has
 *  occurred and cannot be un-crossed by any FORWARD transition — only a
 *  REVOCATION narrows future access, never rewrites this fact). */
export const CROSSED_STATES: readonly ExchangeStatus[] = [
  'EXCHANGED',
  'RECEIPT_ACKNOWLEDGED',
  'COMPARISON_OPEN',
  'COMPLETED',
  'REVOKED_ACCESS_POST_EXCHANGE',
];
export function hasCrossed(status: ExchangeStatus): boolean {
  return CROSSED_STATES.includes(status);
}

/**
 * Legal forward transitions. Deliberately does NOT assume a fixed A-then-B
 * signing order (PRD §11: "State machine implementation should model
 * independent required conditions rather than assume one fixed signature
 * order") — A_SIGNED and B_SIGNED are each reachable from READY_TO_SIGN
 * directly, and EXCHANGED is reachable from EITHER once both are satisfied
 * (the service layer's `isLegalExchangeTransition` used together with the
 * service's own dual-signature check, never state-machine order alone).
 */
const FORWARD_TRANSITIONS: Record<ExchangeStatus, ExchangeStatus[]> = {
  DRAFT: ['A_DEPOSITED', 'WITHDRAWN_PRE_EXCHANGE', 'DECLINED'],
  A_DEPOSITED: ['INVITED', 'WITHDRAWN_PRE_EXCHANGE', 'DECLINED'],
  INVITED: ['B_JOINED', 'WITHDRAWN_PRE_EXCHANGE', 'DECLINED'],
  B_JOINED: ['B_DEPOSITED', 'WITHDRAWN_PRE_EXCHANGE', 'DECLINED'],
  B_DEPOSITED: ['READY_TO_SIGN', 'WITHDRAWN_PRE_EXCHANGE', 'DECLINED', 'ARTIFACT_REPLACEMENT_REQUIRED'],
  READY_TO_SIGN: [
    'A_SIGNED',
    'B_SIGNED',
    'EXCHANGED',
    'WITHDRAWN_PRE_EXCHANGE',
    'DECLINED',
    'SIGNATURE_EXPIRED',
    'ARTIFACT_REPLACEMENT_REQUIRED',
  ],
  A_SIGNED: ['B_SIGNED', 'EXCHANGED', 'WITHDRAWN_PRE_EXCHANGE', 'SIGNATURE_EXPIRED', 'ARTIFACT_REPLACEMENT_REQUIRED'],
  B_SIGNED: ['A_SIGNED', 'EXCHANGED', 'WITHDRAWN_PRE_EXCHANGE', 'SIGNATURE_EXPIRED', 'ARTIFACT_REPLACEMENT_REQUIRED'],
  EXCHANGED: ['RECEIPT_ACKNOWLEDGED', 'REVOKED_ACCESS_POST_EXCHANGE', 'DISPUTED'],
  RECEIPT_ACKNOWLEDGED: ['COMPARISON_OPEN', 'REVOKED_ACCESS_POST_EXCHANGE', 'DISPUTED'],
  COMPARISON_OPEN: ['COMPLETED', 'REVOKED_ACCESS_POST_EXCHANGE', 'DISPUTED'],
  COMPLETED: ['REVOKED_ACCESS_POST_EXCHANGE', 'DISPUTED'],
  // Exception states are terminal for FORWARD progress. DISPUTED may later be
  // resolved by an operator-governed act outside this state machine's own
  // vocabulary (not modelled here — PRD does not specify a dispute-resolution
  // transition, and inventing one would be exactly the kind of unrequested
  // scope this build stays clear of).
  DECLINED: [],
  WITHDRAWN_PRE_EXCHANGE: [],
  ARTIFACT_REPLACEMENT_REQUIRED: ['B_DEPOSITED', 'READY_TO_SIGN'],
  SIGNATURE_EXPIRED: ['READY_TO_SIGN'],
  DISPUTED: [],
  REVOKED_ACCESS_POST_EXCHANGE: [],
};

export function isLegalExchangeTransition(from: ExchangeStatus, to: ExchangeStatus): boolean {
  return (FORWARD_TRANSITIONS[from] ?? []).includes(to);
}

