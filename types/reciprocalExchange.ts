// ─── The isolation-claim guard (PRD §2 — CRITICAL) ──────────────────────────

/**
 * Phrases that assert or imply informational isolation between the parties.
 * ANY generated string (UI copy, receipt summary, evidence record) that
 * contains one of these is a constitutional defect for this capability — it
 * overstates what independent-freeze provenance can honestly establish.
 * Case-insensitive substring match; deliberately broad rather than narrow, on
 * the theory that a false negative here is far more costly than a false
 * positive that makes a legitimate string slightly reword itself.
 */
export const FORBIDDEN_ISOLATION_PHRASES: readonly string[] = [
  'neither party had prior knowledge',
  'no prior knowledge of',
  'no prior access to',
  'without prior knowledge of each other',
  'had no access to the other',
  'had no knowledge of the other',
  'informational isolation',
  'developed in isolation from each other',
  'never discussed',
  'never had access to',
  'blind to each other',
  'without any prior contact',
];

/** The one claim this capability IS allowed to make (PRD §2, §10). */
export const INDEPENDENT_FREEZE_CLAIM =
  'Both artifacts were independently frozen before formal exchange.';

export class IsolationClaimViolation extends Error {
  constructor(public readonly matchedPhrase: string, public readonly text: string) {
    super(
      `Generated text asserts an informational-isolation claim ("${matchedPhrase}"), which this capability ` +
        `must never claim — only "${INDEPENDENT_FREEZE_CLAIM}" is a truthful claim here.`,
    );
    this.name = 'IsolationClaimViolation';
  }
}

/** Throws IsolationClaimViolation if `text` contains a forbidden phrase.
 *  Call this on every generated summary/copy string before it is persisted
 *  to a receipt, evidence record, or rendered UI string for this capability. */
export function assertNoIsolationClaim(text: string): void {
  const lower = text.toLowerCase();
  for (const phrase of FORBIDDEN_ISOLATION_PHRASES) {
    if (lower.includes(phrase)) throw new IsolationClaimViolation(phrase, text);
  }
}

