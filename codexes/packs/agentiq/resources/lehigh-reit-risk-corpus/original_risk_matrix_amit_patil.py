def calculate_combination_risk_score(combination, risk_matrix, risk_types, score_mapping, data_verification, qubes_dict, weights):
    """
    Compute the combined risk score for a given combination of Qubes.
    This function takes the union of records across the Qubes.
    For records present in multiple Qubes, their weight for each risk type is averaged.
    Returns the total weighted score, maximum possible score, percentage score, and list of missing records.
    """
    union_records = {}  # Mapping: record -> list of Qube names in which it appears.
    for qube in combination:
        for record in qubes_dict[qube]:
            union_records.setdefault(record, []).append(qube)

    total_score = 0.0
    max_score = 0.0
    missing_records = []

    for record, qube_list in union_records.items():
        if record not in risk_matrix:
            warnings.warn(f"Record '{record}' from combination {combination} not found in risk_matrix. It is skipped.")
            missing_records.append((combination, record))
            continue

        # For each risk type, average the weight from all Qubes that include this record.
        for risk_type in risk_types:
            avg_weight = np.mean([weights.loc[q, risk_type] for q in qube_list])
            risk_value = risk_matrix[record].get(risk_type, 'Low')
            base_score = score_mapping.get(risk_value, 1)

            # Check if record is verifiable
            is_verified = record in data_verification and len(data_verification[record]) > 0

            # Context-aware adjustment:
            if not is_verified and risk_type != 'Verifiability':
                if risk_value == 'High':
                    adjusted_score = max(base_score - 2, 1)
                elif risk_value == 'Medium':
                    adjusted_score = max(base_score - 1, 1)
                else:
                    adjusted_score = base_score
            else:
                if risk_value == 'Low':
                    adjusted_score = base_score + 0.5
                elif risk_value == 'Medium':
                    adjusted_score = base_score + 0.2
                else:
                    adjusted_score = base_score

            total_score += adjusted_score * avg_weight
            max_score += 3 * avg_weight  # Maximum possible score per risk type is 3.

    percentage_score = (total_score / max_score) * 100 if max_score > 0 else 0
    return total_score, max_score, percentage_score, missing_records

