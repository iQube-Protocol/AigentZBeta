def calculate_risk_score_for_qube(qube, risk_matrix, risk_types, score_mapping, data_verification, weights):
    """
    Calculate the weighted risk score for a single Qube.
    Returns the total weighted score, maximum possible weighted score, percentage score, and a log of missing records.
    """
    total_score = 0.0
    max_score = 0.0
    missing_records = []  # To track records missing in the risk matrix

    for record in qubes_dict[qube]:
        if record not in risk_matrix:
            warnings.warn(f"Record '{record}' from Qube '{qube}' not found in risk_matrix. It is being skipped.")
            missing_records.append((qube, record))
            continue

        # Check if record is verifiable
        is_verified = record in data_verification and len(data_verification[record]) > 0

        for risk_type in risk_types:
            # Get risk level (default to 'Low' if missing)
            risk_value = risk_matrix[record].get(risk_type, 'Low')
            base_score = score_mapping.get(risk_value, 1)

            # Context-aware adjustments:
            if not is_verified and risk_type != 'Verifiability':
                if risk_value == 'High':
                    adjusted_score = max(base_score - 2, 1)
                elif risk_value == 'Medium':
                    adjusted_score = max(base_score - 1, 1)
                else:
                    adjusted_score = base_score
            else:
                if risk_value == 'Low':
                    adjusted_score = base_score + 0.5
                elif risk_value == 'Medium':
                    adjusted_score = base_score + 0.2
                else:
                    adjusted_score = base_score

            # Multiply the adjusted score by the corresponding weight for this Qube and risk type.
            weight = weights.loc[qube, risk_type]
            total_score += adjusted_score * weight
            max_score += 3 * weight  # Maximum score (3) weighted accordingly.

    percentage_score = (total_score / max_score) * 100 if max_score != 0 else 0
    return total_score, max_score, percentage_score, missing_records

def calculate_combined_risk_scores(selected_qubes, risk_matrix, risk_types, score_mapping, data_verification, weights):
    """
    Calculate risk scores for each selected Qube individually.
    Returns a dictionary mapping Qube name to its score details and a list of missing record warnings.
    """
    qube_scores = {}
    all_missing = []
    for qube in selected_qubes:
        total, max_possible, pct, missing = calculate_risk_score_for_qube(qube, risk_matrix, risk_types,
                                                                          score_mapping, data_verification, weights)
        qube_scores[qube] = {"total_score": total, "max_score": max_possible, "percentage": pct}
        all_missing.extend(missing)
    return qube_scores, all_missing

def dynamic_risk_classification(qube_scores):
    """
    Uses K-means clustering to assign risk labels dynamically to the selected Qubes.
    Also computes Z-scores for ranking.
    Returns a dictionary mapping Qube to its dynamic risk label and z-score.
    """
    qube_names = list(qube_scores.keys())
    percentages = np.array([qube_scores[q]["percentage"] for q in qube_names]).reshape(-1, 1)

    # Compute z-scores (if only one Qube, z-score is 0)
    z_scores = zscore(percentages.flatten()) if len(qube_names) > 1 else np.array([0.0])

    # Adjust number of clusters based on the number of Qubes
    num_clusters = min(3, len(qube_names))

    # Handle special case where only one Qube is selected
    if len(qube_names) == 1:
        return {qube_names[0]: {"risk_label": "Medium Risk", "z_score": 0.0}}
    elif len(qube_names) == 2:
        kmeans = KMeans(n_clusters=num_clusters, random_state=42)
        clusters = kmeans.fit_predict(percentages)
        centers = kmeans.cluster_centers_.flatten()
        sorted_clusters = np.argsort(centers)
        cluster_labels = {}
        cluster_labels[sorted_clusters[0]] = "Low Risk"
        cluster_labels[sorted_clusters[1]] = "High Risk"
        dynamic_labels = {}
        for i, qube in enumerate(qube_names):
            dynamic_labels[qube] = {"risk_label": cluster_labels[clusters[i]], "z_score": z_scores[i]}
        return dynamic_labels
    else:
        kmeans = KMeans(n_clusters=num_clusters, random_state=42)
        clusters = kmeans.fit_predict(percentages)
        centers = kmeans.cluster_centers_.flatten()
        sorted_clusters = np.argsort(centers)
        # For three clusters, assign Low, Medium, High respectively
        cluster_labels = {}
        cluster_labels[sorted_clusters[0]] = "Low Risk"
        cluster_labels[sorted_clusters[1]] = "Medium Risk"
        cluster_labels[sorted_clusters[2]] = "High Risk"
        dynamic_labels = {}
        for i, qube in enumerate(qube_names):
            dynamic_labels[qube] = {"risk_label": cluster_labels[clusters[i]], "z_score": z_scores[i]}
        return dynamic_labels

